-- Price configuration (ADR-0007): effective-dated prices per variant, history preserved.
-- Exactly one active row per (variant_id, price_type) is enforced at application level.

CREATE TABLE price_config (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id    BIGINT NOT NULL REFERENCES product_variant(id),
    price_type    VARCHAR(16) NOT NULL,              -- MRP | SELLING | COST
    amount        NUMERIC(12,2) NOT NULL,            -- ex-GST
    gst_pct       NUMERIC(5,2) NOT NULL DEFAULT 0,
    effective_from DATE NOT NULL,
    active        BOOLEAN NOT NULL DEFAULT TRUE,
    notes         VARCHAR(500)
);

