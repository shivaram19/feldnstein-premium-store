-- Gaanugu platform core schema (Phase 1, ADR-0006)
-- Canonical definition: JPA entities follow this file, never the reverse.
-- ANSI SQL only (no Postgres-only types) so the H2 dev profile keeps working.

-- ============ MASTER DATA ============

CREATE TABLE oil_product (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code            VARCHAR(32)  NOT NULL UNIQUE,
    name            VARCHAR(128) NOT NULL,
    oil_source      VARCHAR(32)  NOT NULL,            -- GROUNDNUT | SESAME | COCONUT | MUSTARD | ...
    shelf_life_days INTEGER      NOT NULL DEFAULT 365,
    nutritional_info VARCHAR(2000),                    -- free-text label panel
    active          BOOLEAN      NOT NULL DEFAULT TRUE
);

CREATE TABLE product_variant (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    product_id  BIGINT      NOT NULL REFERENCES oil_product(id),
    sku         VARCHAR(64) NOT NULL UNIQUE,
    size_ml     INTEGER     NOT NULL,
    bottle_type VARCHAR(32) NOT NULL,                  -- GLASS | PET
    cap_type    VARCHAR(32) NOT NULL,                  -- ROPP | LUG | FLIP_TOP
    barcode     VARCHAR(32),
    mrp         NUMERIC(12,2)
);

CREATE TABLE warehouse (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code          VARCHAR(32)  NOT NULL UNIQUE,
    name          VARCHAR(128) NOT NULL,
    type          VARCHAR(32)  NOT NULL,               -- PRODUCTION | FULFILMENT | PARTNER_HUB
    address       VARCHAR(500),
    manager_name  VARCHAR(128),
    manager_phone VARCHAR(16)
);

CREATE TABLE supplier (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code         VARCHAR(32)  NOT NULL UNIQUE,
    type         VARCHAR(16)  NOT NULL,                -- FARMER | PACKAGING
    name         VARCHAR(128) NOT NULL,
    phone        VARCHAR(16),
    address      VARCHAR(500),
    bank_details VARCHAR(500),
    gst          VARCHAR(16),
    active       BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE bull (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code               VARCHAR(32)  NOT NULL UNIQUE,
    name               VARCHAR(128) NOT NULL,
    breed              VARCHAR(64),
    health_status      VARCHAR(32)  NOT NULL DEFAULT 'FIT',   -- FIT | RESTING | TREATMENT | RETIRED
    daily_work_limit_hrs NUMERIC(4,1) NOT NULL DEFAULT 4.0,
    rest_after_days    INTEGER NOT NULL DEFAULT 3,
    acquisition_cost   NUMERIC(14,2),
    last_vet_check     DATE,
    next_vet_check     DATE,
    monthly_feed_cost  NUMERIC(12,2),
    active             BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE press_operator (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(32)  NOT NULL UNIQUE,
    name        VARCHAR(128) NOT NULL,
    phone       VARCHAR(16),
    aadhaar     VARCHAR(12),
    address     VARCHAR(500),
    wage_type   VARCHAR(16) NOT NULL DEFAULT 'DAILY',  -- DAILY | HOURLY
    rate        NUMERIC(12,2) NOT NULL,
    bank_account VARCHAR(64),
    join_date   DATE,
    active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE press (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code                 VARCHAR(32) NOT NULL UNIQUE,
    type                 VARCHAR(64),                  -- wooden gaanugu variant
    beam_condition       VARCHAR(32) NOT NULL DEFAULT 'GOOD',  -- GOOD | FAIR | POOR
    stone_condition      VARCHAR(32) NOT NULL DEFAULT 'GOOD',
    capacity_litres      NUMERIC(10,2),
    year_built           INTEGER,
    last_maintenance     DATE,
    next_maintenance_due DATE,
    status               VARCHAR(32) NOT NULL DEFAULT 'ACTIVE' -- ACTIVE | UNDER_MAINTENANCE | RETIRED
);

CREATE TABLE app_user (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name          VARCHAR(128) NOT NULL,
    email         VARCHAR(128) NOT NULL UNIQUE,
    phone         VARCHAR(16),
    role          VARCHAR(32) NOT NULL,                -- ADMIN | OPERATOR | QC | INVENTORY | SALES (ADR-0005)
    warehouse_id  BIGINT REFERENCES warehouse(id),
    active        BOOLEAN NOT NULL DEFAULT TRUE
);

-- ============ PRODUCTION ============

CREATE TABLE production_batch (
    id                    BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_code            VARCHAR(32) NOT NULL UNIQUE,
    product_id            BIGINT NOT NULL REFERENCES oil_product(id),
    press_date            DATE   NOT NULL,
    seed_type             VARCHAR(64) NOT NULL,
    seed_qty_kg           NUMERIC(12,2) NOT NULL,
    seed_cost_total       NUMERIC(14,2) NOT NULL,
    farmer_id             BIGINT REFERENCES supplier(id),      -- seed source farmer
    bull_id               BIGINT REFERENCES bull(id),
    operator_id           BIGINT REFERENCES press_operator(id),
    press_id              BIGINT REFERENCES press(id),
    oil_yield_litres      NUMERIC(12,2),
    spillage_litres       NUMERIC(12,2) DEFAULT 0,
    status                VARCHAR(32) NOT NULL DEFAULT 'PRESSING',
        -- PRESSING | SEDIMENTATION | BOTTLING_READY | BOTTLING | QC_PENDING | QC_PASSED | RELEASED
    handler_wage_cost     NUMERIC(12,2),
    bull_feed_cost        NUMERIC(12,2),
    press_maintenance_cost NUMERIC(12,2),
    stone_wear_cost       NUMERIC(12,2),
    shed_cost             NUMERIC(12,2),
    packaging_cost        NUMERIC(12,2),
    weather_notes         VARCHAR(500),
    best_before_date      DATE
);

CREATE TABLE bottling_run (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id        BIGINT NOT NULL REFERENCES production_batch(id),
    variant_id      BIGINT NOT NULL REFERENCES product_variant(id),
    bottling_date   DATE NOT NULL,
    bottles_filled  INTEGER NOT NULL DEFAULT 0,
    bottles_damaged INTEGER NOT NULL DEFAULT 0,
    bottles_rejected INTEGER NOT NULL DEFAULT 0,
    warehouse_id    BIGINT NOT NULL REFERENCES warehouse(id),
    bin_location    VARCHAR(64),
    sticker_from    VARCHAR(32),
    sticker_to      VARCHAR(32)
);

CREATE TABLE bull_work_log (
    id                 BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_date          DATE NOT NULL,
    bull_id            BIGINT NOT NULL REFERENCES bull(id),
    batch_id           BIGINT REFERENCES production_batch(id),
    start_time         TIME,
    end_time           TIME,
    hours_worked       NUMERIC(4,2) NOT NULL,
    handler_id         BIGINT REFERENCES press_operator(id),
    health_observation VARCHAR(500)
);

CREATE TABLE operator_attendance (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    work_date      DATE NOT NULL,
    operator_id    BIGINT NOT NULL REFERENCES press_operator(id),
    status         VARCHAR(16) NOT NULL DEFAULT 'PRESENT',  -- PRESENT | ABSENT | HALF_DAY
    check_in       TIME,
    check_out      TIME,
    hours_worked   NUMERIC(4,2),
    press_id       BIGINT REFERENCES press(id),
    batches_worked VARCHAR(128),   -- comma-separated batch codes (denormalised convenience)
    overtime_hrs   NUMERIC(4,2) DEFAULT 0,
    UNIQUE (work_date, operator_id)
);

-- ============ QUALITY ============

CREATE TABLE quality_check (
    id                   BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    batch_id             BIGINT NOT NULL REFERENCES production_batch(id),
    stage                VARCHAR(32) NOT NULL,          -- PRE_PRESS | POST_PRESS | PRE_RELEASE
    moisture_pct         NUMERIC(5,2),
    foreign_matter_pct   NUMERIC(5,2),
    aflatoxin_ppb        NUMERIC(8,2),
    pesticide_residue    VARCHAR(64),                   -- e.g. "BELOW_LODQ" or value
    oil_temp_celsius     NUMERIC(5,2),                  -- cold-press proof: must be < 40
    seal_integrity_ok    BOOLEAN,
    overall_pass         BOOLEAN NOT NULL,
    notes                VARCHAR(1000),
    photo_refs           VARCHAR(1000),                 -- comma-separated object keys / paths
    checked_by           VARCHAR(128),
    checked_at           TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============ INVENTORY ============

CREATE TABLE stock_level (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    variant_id   BIGINT NOT NULL REFERENCES product_variant(id),
    batch_id     BIGINT REFERENCES production_batch(id),
    warehouse_id BIGINT NOT NULL REFERENCES warehouse(id),
    on_hand      INTEGER NOT NULL DEFAULT 0,
    reserved     INTEGER NOT NULL DEFAULT 0,
    unit_cost    NUMERIC(12,2),
    expiry_date  DATE,
    UNIQUE (variant_id, batch_id, warehouse_id)
);

CREATE TABLE stock_movement (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    movement_no     VARCHAR(32) NOT NULL UNIQUE,
    moved_at        TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    type            VARCHAR(32) NOT NULL,
        -- PRODUCTION_IN | PROCUREMENT_IN | TRANSFER_OUT | TRANSFER_IN | ORDER_OUT | ADJUSTMENT_OUT
    variant_id      BIGINT NOT NULL REFERENCES product_variant(id),
    batch_id        BIGINT REFERENCES production_batch(id),
    from_warehouse_id BIGINT REFERENCES warehouse(id),
    to_warehouse_id   BIGINT REFERENCES warehouse(id),
    quantity        INTEGER NOT NULL,
    unit_cost       NUMERIC(12,2),
    reference_type  VARCHAR(32),      -- BATCH | ORDER | TRANSFER | ADJUSTMENT
    reference_id    VARCHAR(64),      -- batch code / order # / transfer # — free-form for the ledger
    reason          VARCHAR(500),
    performed_by    VARCHAR(128)
);

-- ============ PROCUREMENT ============

CREATE TABLE seed_procurement (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    procurement_date DATE NOT NULL,
    seed_type      VARCHAR(64) NOT NULL,
    farmer_id      BIGINT NOT NULL REFERENCES supplier(id),
    qty_kg         NUMERIC(12,2) NOT NULL,
    rate_per_kg    NUMERIC(12,2) NOT NULL,
    total_cost     NUMERIC(14,2) NOT NULL,
    quality_grade  VARCHAR(16),       -- A | B | C
    payment_status VARCHAR(16) NOT NULL DEFAULT 'PENDING',  -- PENDING | PAID
    transport_cost NUMERIC(12,2) DEFAULT 0
);

CREATE TABLE purchase_order (
    id                  BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_number           VARCHAR(32) NOT NULL UNIQUE,
    supplier_id         BIGINT NOT NULL REFERENCES supplier(id),
    delivery_warehouse_id BIGINT NOT NULL REFERENCES warehouse(id),
    order_date          DATE NOT NULL,
    expected_delivery   DATE,
    status              VARCHAR(32) NOT NULL DEFAULT 'DRAFT',
        -- DRAFT | SENT | PARTIALLY_RECEIVED | RECEIVED | CANCELLED
    notes               VARCHAR(500)
);

CREATE TABLE purchase_order_line (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    po_id       BIGINT NOT NULL REFERENCES purchase_order(id),
    item_type   VARCHAR(32) NOT NULL,    -- BOTTLE | CAP | LABEL | OUTER_BOX | OTHER
    spec        VARCHAR(128),            -- e.g. "500ml amber glass, 28mm neck"
    quantity    INTEGER NOT NULL,
    unit_price  NUMERIC(12,2) NOT NULL,
    tax_pct     NUMERIC(5,2) DEFAULT 0
);

CREATE TABLE goods_receipt (
    id               BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grn_number       VARCHAR(32) NOT NULL UNIQUE,
    po_id            BIGINT NOT NULL REFERENCES purchase_order(id),
    receipt_date     DATE NOT NULL,
    delivery_note_no VARCHAR(64),
    condition_note   VARCHAR(500),
    received_by      VARCHAR(128)
);

CREATE TABLE goods_receipt_line (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    grn_id        BIGINT NOT NULL REFERENCES goods_receipt(id),
    po_line_id    BIGINT NOT NULL REFERENCES purchase_order_line(id),
    qty_received  INTEGER NOT NULL DEFAULT 0,
    qty_damaged   INTEGER NOT NULL DEFAULT 0,
    qty_short     INTEGER NOT NULL DEFAULT 0
);
