-- Inventory suite extension (ADR-0008 alerts, ADR-0009 stock counts, ADR-0010 audit, ADR-0011 reports+settings)
-- ANSI SQL only (no Postgres-only types) so the H2 dev profile keeps working.

-- ============ ALERTS (ADR-0008) ============

CREATE TABLE alert_rule (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_type       VARCHAR(32) NOT NULL,               -- LOW_STOCK | NEAR_EXPIRY | QC_OVERDUE
    scope_ref       VARCHAR(64),                        -- SKU / product code / 'ALL'; NULL = all
    threshold_value INTEGER NOT NULL,
    active          BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE alert (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    rule_id    BIGINT REFERENCES alert_rule(id),
    alert_type VARCHAR(32) NOT NULL,                    -- LOW_STOCK | NEAR_EXPIRY | QC_OVERDUE
    severity   VARCHAR(16) NOT NULL DEFAULT 'WARNING',  -- INFO | WARNING | CRITICAL
    message    VARCHAR(500) NOT NULL,
    ref_type   VARCHAR(32),                             -- STOCK_LEVEL | BATCH
    ref_id     VARCHAR(64),
    status     VARCHAR(16) NOT NULL DEFAULT 'OPEN',     -- OPEN | DISMISSED | RESOLVED
    created_at TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    resolved_at TIMESTAMP
);

-- ============ SETTINGS (ADR-0011) ============

CREATE TABLE app_setting (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    setting_key VARCHAR(64) NOT NULL UNIQUE,
    setting_value VARCHAR(500),
    value_type  VARCHAR(16) NOT NULL DEFAULT 'STRING',  -- STRING | INTEGER | DECIMAL | BOOLEAN
    description VARCHAR(500)
);

-- ============ AUDIT (ADR-0010) ============

CREATE TABLE audit_event (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor       VARCHAR(128) NOT NULL,
    action      VARCHAR(64) NOT NULL,
    entity_type VARCHAR(64),
    entity_id   VARCHAR(64),
    detail_json VARCHAR(4000),
    at          TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP
);

-- ============ STOCK COUNTS (ADR-0009) ============

CREATE TABLE stock_count_plan (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_code    VARCHAR(32) NOT NULL UNIQUE,
    scope_desc   VARCHAR(200),
    warehouse_id BIGINT REFERENCES warehouse(id),
    status       VARCHAR(16) NOT NULL DEFAULT 'PLANNED', -- PLANNED | IN_PROGRESS | COMPLETED | RECONCILED
    created_by   VARCHAR(128),
    planned_date DATE,
    completed_at TIMESTAMP
);

CREATE TABLE stock_count_line (
    id             BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    plan_id        BIGINT NOT NULL REFERENCES stock_count_plan(id),
    stock_level_id BIGINT NOT NULL REFERENCES stock_level(id),
    system_qty     INTEGER NOT NULL,
    counted_qty    INTEGER,
    variance       INTEGER,
    counted_by     VARCHAR(128)
);

-- ============ REPORTS (ADR-0011) ============

CREATE TABLE report_schedule (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    name        VARCHAR(128) NOT NULL,
    report_type VARCHAR(64) NOT NULL,
        -- INVENTORY_SUMMARY | PRODUCTION_YIELD | EXPIRY_FEFO | PROCUREMENT_SPEND | LEDGER_CUSTOM
    params_json VARCHAR(2000),
    frequency   VARCHAR(16) NOT NULL,                   -- DAILY | WEEKLY | MONTHLY
    next_run    DATE,
    active      BOOLEAN NOT NULL DEFAULT TRUE
);

CREATE TABLE report_run (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    schedule_id BIGINT REFERENCES report_schedule(id),
    report_type VARCHAR(64) NOT NULL,
    params_json VARCHAR(2000),
    run_at      TIMESTAMP NOT NULL DEFAULT CURRENT_TIMESTAMP,
    csv_content CLOB
);

